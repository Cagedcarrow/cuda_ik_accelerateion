#!/usr/bin/env python3
from __future__ import annotations

import subprocess

from common_metrics import COMMON_FIELDS, INPUTS, RESULTS, RUNNER, read_csv, row_from_runner_summary, write_csv

N_VALUES = [100, 500, 1000]
K_VALUES = [1, 16]
TARGET_TYPES = ["wrist_singular", "elbow_singular", "shoulder_singular"]
WARMUP = 10
REPEAT = 30
MAX_ITER = 60


def run_one(target_type: str, n: int, k: int) -> dict[str, object]:
    target = INPUTS / "near_singular" / f"targets_{target_type}_N{n}_T4x4_f64.raw"
    seeds = INPUTS / "near_singular" / f"seeds_{target_type}_N{n}_K{k}_q_f64.raw"
    best = RESULTS / f"near_singular_best_{target_type}_N{n}_K{k}.csv"
    summary = RESULTS / f"near_singular_summary_{target_type}_N{n}_K{k}.csv"
    timing = RESULTS / f"near_singular_timing_{target_type}_N{n}_K{k}.csv"
    if not target.exists() or not seeds.exists():
        raise FileNotFoundError(f"missing input for {target_type} N={n} K={k}; run generate_special_targets.py")
    if not summary.exists():
        cmd = [
            str(RUNNER),
            "--mode", "v4_static",
            "--variant", "opt4c_block_target",
            "--limit-gradient", "analytic",
            "--graph-mode", "off",
            "--precision-mode", "fp64",
            "--fallback-mode", "none",
            "--targets", str(target),
            "--seeds", str(seeds),
            "--N", str(n),
            "--K", str(k),
            "--max-iter", str(MAX_ITER),
            "--repeat", str(REPEAT),
            "--warmup", str(WARMUP),
            "--best-csv", str(best),
            "--summary-csv", str(summary),
            "--timing-csv", str(timing),
        ]
        print("running", target_type, "N", n, "K", k, flush=True)
        subprocess.run(cmd, check=True, cwd=RUNNER.parents[1])
    row = read_csv(summary)[0]
    normalized = row_from_runner_summary(row, f"OPT4C-K{k}", "near_singular", target_type)
    normalized["K"] = k
    normalized["notes"] = "targets generated by FK from near-singular joint samples"
    return normalized


def main() -> int:
    if not RUNNER.exists():
        raise FileNotFoundError(f"runner not found: {RUNNER}")
    rows = []
    for target_type in TARGET_TYPES:
        for n in N_VALUES:
            for k in K_VALUES:
                rows.append(run_one(target_type, n, k))
    out = RESULTS / "near_singular_summary.csv"
    write_csv(out, rows, COMMON_FIELDS)
    print(f"wrote {out} rows={len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

